import secrets
import streamlit as st

# --- Constants ---
# We draw 17 bytes (136 bits) from the CSPRNG.
# We use 12 words * 11 bits/word = 132 bits, discarding the remaining 4 bits.
# This yields ~132 bits of combinatorial entropy, which exceeds the 128-bit target.
ENTROPY_BYTES = 17  # 136 bits pulled from CSPRNG
BITS_PER_WORD = 11  # 2^11 = 2048, matches minimum word list size
WORDS_NEEDED = 12
MIN_WORDLIST_SIZE = 1 << BITS_PER_WORD  # 2048
MAX_HISTORY = 3  # current generation + 2 previous ones kept in memory

st.set_page_config(page_title="Mnemonic Generator", page_icon="🔐")
st.title("🔐 12-Word CSPRNG Mnemonic Generator")

st.warning(
    "⚠️ **Run this locally / offline only.** This tool generates secret key "
    "material. If deployed as a hosted web app, the phrase can be exposed via "
    "network transit, server logs, reverse proxies, or browser caches/extensions. "
    "Do not use a phrase generated by a networked instance for real funds. "
    "Note: this app keeps your last 3 generations in memory for this session "
    "only (nothing is written to disk); refreshing the page clears them."
)

st.caption(
    f"Draws {ENTROPY_BYTES * 8} bits from the OS CSPRNG and slices them into "
    f"{WORDS_NEEDED} × {BITS_PER_WORD}-bit chunks (~{WORDS_NEEDED * BITS_PER_WORD} "
    "bits of entropy). Note: this list is not BIP-39 and has no checksum word — "
    "it is not compatible with standard hardware/software wallets."
)

raw_text = st.text_area(f"Word List (must contain at least {MIN_WORDLIST_SIZE} unique words):")
words = list(dict.fromkeys(
    w.strip().lower() for w in raw_text.replace(",", " ").split() if w.strip()
))

if len(words) < MIN_WORDLIST_SIZE:
    st.error(
        f"Current pool: **{len(words)}** words. You MUST provide at least "
        f"**{MIN_WORDLIST_SIZE} unique words** so every {BITS_PER_WORD}-bit index "
        "(0–2047) maps to a distinct word with zero modulo bias."
    )
else:
    st.success(f"Pool size verified: **{len(words)}** words (≥ {BITS_PER_WORD} bits/word).")

if st.button("Generate Secure 12 Words"):
    if len(words) < MIN_WORDLIST_SIZE:
        st.error("Cannot generate: word list does not meet the security threshold.")
    else:
        # Fetch entropy directly from the OS CSPRNG via secrets module.
        raw_bytes = secrets.token_bytes(ENTROPY_BYTES)
        bit_string = bin(int.from_bytes(raw_bytes, byteorder="big"))[2:].zfill(ENTROPY_BYTES * 8)

        selected_words = []
        for i in range(WORDS_NEEDED):
            chunk = bit_string[i * BITS_PER_WORD : (i + 1) * BITS_PER_WORD]
            index = int(chunk, 2)  # range 0–2047, no modulo needed since len(words) >= 2048
            selected_words.append(words[index])

        st.code(" ".join(selected_words), language=None)
        st.info(
            "Entropy source: OS CSPRNG (`secrets.token_bytes`). Because the word pool is "
            "guaranteed to contain at least 2048 entries, each 11-bit index maps "
            "1:1 onto a word — no modulo reduction, no bias."
        )
